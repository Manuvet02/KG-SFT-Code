"""
eval_generation/llm_judge.py

LLM-as-a-judge metric

Metrics :
    correctness  -- does the generated query correctly 
    efficiency    -- does it avoid unnecessary joins, subqueries compared to the golden query
    readability    -- is it well-structured, sensible variable names, not needlessly convoluted
"""

from __future__ import annotations

import asyncio
import json
import os
import re
import sys

_this_dir = os.path.dirname(os.path.abspath(__file__))
_app_dir = os.path.dirname(_this_dir)       # backend/app
_backend_dir = os.path.dirname(_app_dir)    # backend
for _p in (_app_dir, _backend_dir):
    if _p not in sys.path:
        sys.path.insert(0, _p)


SYSTEM_PROMPT = """You are an expert SPARQL and knowledge-graph evaluator. \
You judge whether a SPARQL query generated by an NL-to-SPARQL system correctly \
answers a natural language question, over KG-SFT (a knowledge graph of sports \
facilities and public transport in Trentino, prefix sft:).

You are given the question, a reference ("golden") query, and the system's \
generated query. Score the generated query on three dimensions, each from \
0.0 to 1.0:

- correctness: does the generated query correctly implement the INTENT of \
the question, judged against the golden query's intent? Different variable \
names, equivalent join orderings, or a differently-shaped but semantically \
equivalent query are all fine -- judge meaning, not surface form. A query \
that answers a different question, drops a filter/constraint present in the \
golden query, or queries the wrong class/property should score low.
- efficiency: does the generated query avoid unnecessary joins, subqueries, \
or overly broad triple patterns compared to the golden query? A query doing \
more work than necessary to answer the question scores lower.
- readability: is the generated query well-structured, with sensible \
variable names and reasonable formatting, not needlessly convoluted?

Respond with ONLY a JSON object, nothing else:
{"correctness": <float>, "efficiency": <float>, "readability": <float>, "rationale": "<one short sentence>"}"""


def build_judge_prompt(question: str, golden: str, generated: str) -> str:
    return f"""Question: {question}

Golden query:
{golden}

Generated query:
{generated}

Score the generated query now."""


# Response parsing -- robust to a model wrapping the JSON in prose/markdown
def parse_judge_response(raw: str) -> dict | None:
    text = raw.strip()
    # strip ```json ... ``` fences if present
    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip(), flags=re.MULTILINE)

    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", text, re.DOTALL)
        if not match:
            return None
        try:
            data = json.loads(match.group(0))
        except json.JSONDecodeError:
            return None

    required = ("correctness", "efficiency", "readability")
    if not all(k in data for k in required):
        return None
    try:
        for k in required:
            data[k] = max(0.0, min(1.0, float(data[k])))
    except (TypeError, ValueError):
        return None
    data.setdefault("rationale", "")
    return data

async def judge_one(ask_llm_fn, inst: dict, max_retries: int = 2) -> dict | None:
    prompt = build_judge_prompt(
        inst["generated_question"], inst["golden_sparql"], inst["generated_sparql"]
    )
    for attempt in range(max_retries + 1):
        try:
            raw = await ask_llm_fn(prompt, system=SYSTEM_PROMPT)
        except Exception as exc:
            wait = 2 * (attempt + 1)
            print(f"[llm_judge] request failed ({exc!r}), retrying in {wait}s "
                  f"(attempt {attempt + 1}/{max_retries + 1})")
            await asyncio.sleep(wait)
            continue

        parsed = parse_judge_response(raw)
        if parsed is not None:
            return parsed
        print(f"[llm_judge] malformed judge output on {inst['id']} (attempt {attempt + 1})")
    return None


async def judge_all(
    ask_llm_fn,
    runs: list[dict],
    out_path: str,
    max_retries: int = 2,
    concurrency: int = 3,
) -> list[dict]:
    semaphore = asyncio.Semaphore(concurrency)
    write_lock = asyncio.Lock()
    results: list[dict] = []

    already_done: set[str] = set()
    if os.path.exists(out_path):
        already_done = {r["id"] for r in load_jsonl(out_path)}
        if already_done:
            print(f"[llm_judge] resuming: {len(already_done)} already judged in {out_path}")

    async def worker(inst: dict):
        if inst["id"] in already_done:
            return
        async with semaphore:
            print(f"[llm_judge] judging {inst['id']} ...")
            scores = await judge_one(ask_llm_fn, inst, max_retries)
        if scores is None:
            print(f"[llm_judge] gave up on {inst['id']}")
            return

        record = {
            "id": inst["id"],
            "cq_ref": inst.get("cq_ref", ""),
            **scores,
        }
        print(f"[llm_judge] done  {inst['id']}: "
              f"correctness={scores['correctness']:.2f} "
              f"efficiency={scores['efficiency']:.2f} "
              f"readability={scores['readability']:.2f}")
        results.append(record)
        async with write_lock:
            with open(out_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(record, ensure_ascii=False) + "\n")

    outcomes = await asyncio.gather(*(worker(inst) for inst in runs), return_exceptions=True)
    for inst, outcome in zip(runs, outcomes):
        if isinstance(outcome, Exception):
            print(f"[llm_judge] worker crashed on {inst['id']}: {outcome!r}")

    return results


def load_jsonl(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def summarize(results: list[dict]) -> dict:
    if not results:
        return {}
    dims = ("correctness", "efficiency", "readability")
    summary = {dim: sum(r[dim] for r in results) / len(results) for dim in dims}
    summary["n"] = len(results)
    return summary


async def main():
    from mcp.openrouter_client import ask_llm, LOCAL_MODEL , MODEL 

    print(f"[llm_judge] using model: {MODEL}")
    runs = load_jsonl("agent_runs.jsonl")
    print(f"[llm_judge] {len(runs)} agent runs to judge")

    out_path = "llm_judge_results.jsonl"
    await judge_all(ask_llm, runs, out_path)

    all_results = load_jsonl(out_path)
    all_results.sort(key=lambda r: r["id"])
    with open(out_path, "w", encoding="utf-8") as f:
        for rec in all_results:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    summary = summarize(all_results)
    with open("llm_judge_summary.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print(f"\n[llm_judge] {len(all_results)}/{len(runs)} judged -> {out_path}")
    print("[llm_judge] summary (mean across all judged instances):")
    for k, v in summary.items():
        print(f"  {k}: {v:.3f}" if k != "n" else f"  n: {v}")


if __name__ == "__main__":
    asyncio.run(main())
